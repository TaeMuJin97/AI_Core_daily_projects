# 3. 메타데이터 결합 결과 검증
# ============================================================

def validate_join(clean, joined):
    """정제 데이터와 메타데이터 결합 결과를 검사합니다.

    [검사 항목]

    1. 결합 결과에 필수 열이 존재하는가?
    2. 결합 전후 행 개수가 동일한가?
    3. 실행 ID의 순서가 유지되었는가?
    4. 모든 실행 기록이 메타데이터와 연결되었는가?
    5. 토큰 사용 비용이 정확하게 계산되었는가?

    [중요 개념]

    다대일(many-to-one) 결합에서는
    여러 실행 기록이 하나의 메타데이터와 연결됩니다.

    정상적으로 결합했다면 실행 기록의 행 개수가
    임의로 증가하거나 감소해서는 안 됩니다.
    """

    # --------------------------------------------------------
    # [1단계] 필수 열 검사
    # --------------------------------------------------------

    # 결합 결과에 반드시 존재해야 하는 열입니다.
    #
    # run_id:
    #   → 실행 기록 식별자
    #
    # _merge:
    #   → 데이터 결합 성공 여부
    #
    # cost_unit:
    #   → 계산된 가상 토큰 사용 비용
    #
    # tokens:
    #   → 사용 토큰 수
    #
    # rate_per_1k:
    #   → 토큰 1,000개당 가상 단가
    need = {
        "run_id",
        "_merge",
        "cost_unit",
        "tokens",
        "rate_per_1k"
    }

    # 필수 열이 하나라도 없으면 오류를 반환합니다.
    if not need.issubset(joined.columns):
        return ["결합 필수 열 누락"]

    # 결합 결과에서 발견된 오류를 저장할 리스트입니다.
    errors = []

    # --------------------------------------------------------
    # [2단계] 결합 전후 행 개수와 ID 순서 비교
    # --------------------------------------------------------

    # len(joined) != len(clean)
    #   → 결합 전후 실행 기록 수가 달라졌는지 검사합니다.
    #
    # joined["run_id"].tolist()
    #   → 결합 결과의 실행 ID를 리스트로 변환합니다.
    #
    # clean["run_id"].tolist()
    #   → 정제 데이터의 실행 ID를 리스트로 변환합니다.
    #
    # 두 리스트를 비교하면 ID 값뿐 아니라
    # 원래의 행 순서가 유지되었는지도 확인할 수 있습니다.
    #
    # 예:
    # clean  = ["001", "002", "003"]
    # joined = ["001", "003", "002"]
    #
    # 행 개수는 동일하지만 순서가 바뀌었으므로 오류입니다.
    if (
        len(joined) != len(clean)
        or joined["run_id"].tolist() != clean["run_id"].tolist()
    ):
        errors.append("결합으로 실행 행 또는 순서가 바뀜")

    # --------------------------------------------------------
    # [3단계] 메타데이터 연결 상태 검사
    # --------------------------------------------------------

    # _merge 열은 Pandas의 merge(indicator=True)에서 생성됩니다.
    #
    # 주요 값:
    #
    # both:
    #   → 양쪽 데이터에서 일치하는 값이 존재함
    #
    # left_only:
    #   → 왼쪽 데이터에만 존재함
    #
    # joined["_merge"].eq("both")
    #   → 각 실행 기록이 정상적으로 연결되었는지 확인합니다.
    #
    # .all()
    #   → 모든 행의 연결 상태가 both인지 검사합니다.
    #
    # 하나라도 연결되지 않은 기록이 있으면 오류를 추가합니다.
    if not joined["_merge"].eq("both").all():
        errors.append("미연결 역할 존재")

    # --------------------------------------------------------
    # [4단계] 토큰 사용 비용 재계산
    # --------------------------------------------------------

    # 결합 결과에 저장된 cost_unit이 올바른지 확인하기 위해
    # 원래 계산식으로 비용을 다시 계산합니다.
    #
    # 비용 계산 공식:
    #
    # cost_unit = tokens / 1000 × rate_per_1k
    #
    # 예:
    # tokens = 2000
    # rate_per_1k = 0.5
    #
    # 비용 = 2000 / 1000 × 0.5 = 1.0
    #
    # calc에는 다시 계산한 비용이 저장됩니다.
    calc = joined["tokens"] / 1000 * joined["rate_per_1k"]

    # --------------------------------------------------------
    # [5단계] 재계산한 비용과 제출된 비용 비교
    # --------------------------------------------------------

    # np.allclose():
    #   → 두 숫자 배열이 허용 오차 범위 내에서
    #     모두 같은지 검사합니다.
    #
    # to_numpy(float):
    #   → Pandas Series를 NumPy 실수형 배열로 변환합니다.
    #
    # equal_nan=True:
    #   → 같은 위치에 NaN이 있다면 동일한 결측값으로 인정합니다.
    #
    # 비용이 누락된 경우 NaN을 임의로 0으로 바꾸지 않습니다.
    #
    # 계산 결과와 제출 결과가 다르면 오류를 추가합니다.
    if not np.allclose(
        calc.to_numpy(float),
        joined["cost_unit"].to_numpy(float),
        equal_nan=True
    ):
        errors.append("가상 비용 계산 불일치")

    # 검증 결과를 오류 목록으로 반환합니다.
    return errors


