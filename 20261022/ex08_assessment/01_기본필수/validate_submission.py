def verify_png(path):
    """제출된 이미지가 정상적인 PNG인지 검사합니다.

    [검사할 내용]

    1. 이미지 파일을 정상적으로 열 수 있는가?
    2. 이미지 구조가 손상되지 않았는가?
    3. 이미지 형식이 PNG인가?
    4. 이미지의 가로·세로 크기가 각각 200픽셀 이상인가?

    [반환값]

    True  → 이미지 검증 통과
    False → 이미지 검증 실패

    ※ 그래프의 통계적 정확성이나 축 설명의 적절성까지
      확인하는 함수는 아닙니다.
    """

    # try:
    #   → 이미지 파일을 여는 과정에서 발생할 수 있는
    #     오류를 처리하기 위해 사용합니다.
    try:

        # ----------------------------------------------------
        # [1단계] 이미지 파일 구조 검사
        # ----------------------------------------------------

        # Image.open(path):
        #   → 지정한 경로의 이미지 파일을 엽니다.
        #
        # with:
        #   → 작업이 끝나면 파일 자원을 자동으로 정리합니다.
        #
        # image.verify():
        #   → 이미지 파일의 구조가 올바른지 확인합니다.
        #
        # verify()는 이미지를 실제 화면에 표시하는 함수가
        # 아니라 파일 구조를 검사하는 함수입니다.
        with Image.open(path) as image:
            image.verify()

        # ----------------------------------------------------
        # [2단계] 이미지 형식과 크기 검사
        # ----------------------------------------------------

        # verify() 이후에는 파일을 다시 열어
        # 이미지 형식과 크기 정보를 확인합니다.
        with Image.open(path) as image:

            # image.format:
            #   → 이미지 파일의 형식을 반환합니다.
            #   → 예: PNG, JPEG 등
            #
            # image.size:
            #   → (가로 픽셀, 세로 픽셀) 튜플을 반환합니다.
            #
            # 예:
            # (800, 450)
            #
            # min(image.size):
            #   → 가로와 세로 중 더 작은 값을 가져옵니다.
            #
            # min(image.size) >= 200:
            #   → 가로와 세로가 모두 200픽셀 이상인지 검사합니다.
            #
            # 두 조건을 모두 만족하면 True를 반환합니다.
            return (
                image.format == "PNG"
                and min(image.size) >= 200
            )

    # --------------------------------------------------------
    # [3단계] 이미지 관련 오류 처리
    # --------------------------------------------------------

    # OSError:
    #   → 파일을 열 수 없거나 이미지 처리에 문제가 있는 경우
    #
    # ValueError:
    #   → 이미지 값 또는 형식 관련 오류가 발생한 경우
    #
    # 오류가 발생하면 프로그램을 종료하지 않고
    # 검증 실패(False)를 반환합니다.
    except (OSError, ValueError):
        return False


