# 5. 최종 프로젝트 제출 폴더 검사
# ============================================================

def inspect_project(project, level="basic"):
    """제출된 프로젝트 폴더의 파일과 분석 결과를 검증합니다.

    [입력]

    project
        → 검사할 프로젝트 폴더의 경로

    level
        → 프로젝트 난이도
        → basic / applied / advanced

    [주요 검사]

    - 필수 파일 존재 여부
    - 정제 데이터와 집계 결과
    - 메타데이터 결합 결과(응용/심화)
    - PNG 이미지 파일
    - 보고서 미작성 항목
    - 미구현 코드
    - tests 폴더 존재 여부

    [중요]

    이 함수는 제출 폴더의 파일을 읽어 검사합니다.

    프로젝트의 코드를 직접 실행하거나
    Git 저장소를 생성하거나 커밋하지 않습니다.

    [반환값]

    {
        "automatic_errors": [...],
        "manual_review": [...],
        "notice": "..."
    }

    automatic_errors:
        → 자동 검사에서 발견된 오류 목록

    manual_review:
        → 강사가 직접 확인해야 할 항목

    notice:
        → 자동 검사 결과에 대한 안내 문구
    """

    # --------------------------------------------------------
    # [1단계] 프로젝트 폴더 경로 변환
    # --------------------------------------------------------

    # Path(project):
    #   → 프로젝트 경로를 Path 객체로 변환합니다.
    #
    # resolve():
    #   → 절대 경로로 변환합니다.
    #
    # 예:
    # ./my_project
    #       ↓
    # C:/AI_Project/my_project
    project = Path(project).resolve()

    # --------------------------------------------------------
    # [2단계] 기본필수 제출 파일 목록 정의
    # --------------------------------------------------------

    # required:
    #   → 반드시 제출해야 하는 파일의 상대 경로 목록입니다.
    #
    # 각 경로는 project 폴더를 기준으로 합니다.
    #
    # 예:
    # "main.py"
    #   → project/main.py
    #
    # "out/summary.json"
    #   → project/out/summary.json
    required = [
        "main.py",
        "data/agent_runs.csv",
        "out/clean_runs.csv",
        "out/summary.json",
        "out/charts/latency_by_agent.png",
        "out/charts/latency_hist.png",
        "reports/eda_report.md",
        "README.md",
        "requirements.txt",
        ".gitignore"
    ]

    # 주요 제출 파일의 역할:
    #
    # main.py:
    #   → 전체 분석 파이프라인 실행 파일
    #
    # data/agent_runs.csv:
    #   → 분석에 사용한 입력 데이터
    #
    # out/clean_runs.csv:
    #   → 정제 결과
    #
    # out/summary.json:
    #   → 집계 통계
    #
    # out/charts/*.png:
    #   → 데이터 시각화 결과
    #
    # reports/eda_report.md:
    #   → 분석 보고서
    #
    # README.md:
    #   → 프로젝트 소개 및 실행 방법
    #
    # requirements.txt:
    #   → 필요한 파이썬 패키지 목록
    #
    # .gitignore:
    #   → Git에서 추적하지 않을 파일의 규칙

    # --------------------------------------------------------
    # [3단계] 응용/심화 추가 제출 파일
    # --------------------------------------------------------

    # level이 basic이 아니면 추가 파일을 요구합니다.
    #
    # applied 또는 advanced인 경우 추가 검사합니다.
    if level != "basic":

        # += 연산자는 기존 리스트에 항목을 추가합니다.
        #
        # 추가 파일:
        #
        # agents_meta.json:
        #   → 에이전트별 단가 등의 메타데이터
        #
        # joined_runs.csv:
        #   → 실행 기록과 메타데이터의 결합 결과
        #
        # pivot.csv:
        #   → 에이전트×상태별 피벗 테이블
        #
        # tokens_latency.png:
        #   → 토큰 사용량과 실행 시간의 산점도
        required += [
            "data/agents_meta.json",
            "out/joined_runs.csv",
            "out/pivot.csv",
            "out/charts/tokens_latency.png"
        ]

    # 참고:
    # 현재 검증 코드에서는 advanced에도
    # applied와 동일한 추가 파일 목록을 요구합니다.
    #
    # daily.csv와 daily_latency.png의 존재 여부는
    # required 목록에 별도로 추가되어 있지 않습니다.

    # --------------------------------------------------------
    # [4단계] 필수 파일 존재 여부 검사
    # --------------------------------------------------------

    # 리스트 컴프리헨션(List Comprehension)을 사용합니다.
    #
    # 기본 구조:
    # [표현식 for 변수 in 반복대상 if 조건]
    #
    # (project / name):
    #   → 프로젝트 폴더와 상대 파일 경로를 결합합니다.
    #
    # .is_file():
    #   → 해당 경로에 일반 파일이 존재하는지 검사합니다.
    #
    # not:
    #   → 파일이 존재하지 않는 경우 True가 됩니다.
    #
    # 누락된 파일마다 다음 형태의 오류를 생성합니다.
    #
    # "파일 누락: out/summary.json"
    errors = [
        "파일 누락: " + name
        for name in required
        if not (project / name).is_file()
    ]

    # --------------------------------------------------------
    # [5단계] 필수 파일이 누락된 경우
    # --------------------------------------------------------

    # errors 리스트에 항목이 존재하면
    # 필요한 제출 파일이 하나 이상 누락된 상태입니다.
    #
    # 파일이 없는 상태에서 데이터를 읽으려고 하면
    # 추가적인 오류가 발생할 수 있습니다.
    #
    # 따라서 이후 검사를 진행하지 않고
    # 누락 파일 목록과 재검사 안내를 반환합니다.
    if errors:
        return {
            "automatic_errors": errors,
            "manual_review": ["누락 자료 보완 후 재검사"]
        }

    # --------------------------------------------------------
    # [6단계] 정제 CSV 파일 읽기
    # --------------------------------------------------------

    # pd.read_csv():
    #   → CSV 파일을 Pandas DataFrame으로 읽습니다.
    #
    # dtype={"run_id": "string"}:
    #   → 실행 ID를 문자열로 유지합니다.
    #
    # 예:
    # "000123"을 정수로 읽으면 123으로 변할 수 있으므로
    # ID는 문자열로 명시합니다.
    #
    # encoding="utf-8-sig":
    #   → UTF-8 BOM이 포함된 CSV를 올바르게 읽습니다.
    clean = pd.read_csv(
        project / "out/clean_runs.csv",
        dtype={"run_id": "string"},
        encoding="utf-8-sig"
    )

    # --------------------------------------------------------
    # [7단계] JSON의 비표준 숫자 표현 거부
    # --------------------------------------------------------

    # JSON 표준에서는 다음과 같은 숫자 표현을 허용하지 않습니다.
    #
    # NaN
    # Infinity
    # -Infinity
    #
    # JSON에서 값이 없다는 의미는 null을 사용합니다.
    #
    # 아래 reject()는 비표준 숫자 표현을 발견하면
    # ValueError를 발생시키는 함수입니다.
    def reject(value):
        raise ValueError("비표준 JSON 수치: " + value)

    # --------------------------------------------------------
    # [8단계] 요약 JSON 파일 읽기
    # --------------------------------------------------------

    # read_text(encoding="utf-8"):
    #   → JSON 파일 내용을 문자열로 읽습니다.
    #
    # json.loads():
    #   → JSON 문자열을 파이썬 객체로 변환합니다.
    #
    # parse_constant=reject:
    #   → NaN, Infinity 등의 비표준 숫자 표현을
    #     발견하면 reject()를 호출합니다.
    #
    # 이번 프로젝트의 summary.json은
    # 리스트 형태의 JSON 데이터를 기대합니다.
    records = json.loads(
        (project / "out/summary.json").read_text(encoding="utf-8"),
        parse_constant=reject
    )

    # --------------------------------------------------------
    # [9단계] 정제 데이터와 집계 결과 검사
    # --------------------------------------------------------

    # pd.DataFrame(records):
    #   → JSON에서 읽은 리스트를 DataFrame으로 변환합니다.
    #
    # validate_tables():
    #   → 정제 데이터와 집계 결과가 일치하는지 검사합니다.
    #
    # 반환된 오류 목록을 기존 errors 리스트에 추가합니다.
    #
    # +=:
    #   → 리스트의 뒤에 다른 리스트의 항목을 추가합니다.
    errors += validate_tables(
        clean,
        pd.DataFrame(records)
    )

    # --------------------------------------------------------
    # [10단계] 응용/심화 메타데이터 결합 결과 검사
    # --------------------------------------------------------

    # basic이 아닌 경우 joined_runs.csv를 추가 검사합니다.
    if level != "basic":

        # 결합 결과 CSV를 읽습니다.
        #
        # run_id는 문자열로 유지하여
        # ID의 앞자리 0이 손실되지 않도록 합니다.
        joined = pd.read_csv(
            project / "out/joined_runs.csv",
            dtype={"run_id": "string"},
            encoding="utf-8-sig"
        )

        # 정제 데이터와 결합 결과의 행 수,
        # ID 순서, 연결 상태, 비용 계산 결과를 검사합니다.
        errors += validate_join(clean, joined)

    # --------------------------------------------------------
    # [11단계] PNG 이미지 파일 검사
    # --------------------------------------------------------

    # (project / "out/charts"):
    #   → 그래프 이미지가 저장된 폴더입니다.
    #
    # glob("*.png"):
    #   → 해당 폴더의 PNG 확장자 파일을 찾습니다.
    #
    # for 문으로 각 PNG 파일을 검사합니다.
    for path in (project / "out/charts").glob("*.png"):

        # verify_png():
        #   → 이미지 구조, 형식, 최소 크기를 검사합니다.
        #
        # 검사 결과가 False이면 오류를 추가합니다.
        #
        # 예:
        # "잘못된 이미지: latency_hist.png"
        if not verify_png(path):
            errors.append("잘못된 이미지: " + path.name)

    # --------------------------------------------------------
    # [12단계] 분석 보고서 검사
    # --------------------------------------------------------

    # 분석 보고서(eda_report.md)를 UTF-8 문자열로 읽습니다.
    #
    # Markdown(.md):
    #   → 제목, 표, 목록 등을 텍스트 형식으로
    #     작성할 수 있는 문서 파일 형식입니다.
    report = (project / "reports/eda_report.md").read_text(
        encoding="utf-8"
    )

    # 보고서에 TODO 또는 [작성]이라는 문구가 남아 있는지 확인합니다.
    #
    # 일반적으로 해당 문구는 아직 작성하지 않은 항목을
    # 표시하기 위한 임시 문구로 사용합니다.
    #
    # 예:
    # "TODO: 분석 결과 작성"
    # "[작성] 결과 해석"
    #
    # 하나라도 존재하면 미작성 항목이 남은 것으로 판단합니다.
    if "TODO" in report or "[작성]" in report:
        errors.append("분석 보고서에 미작성 표시가 남음")

    # --------------------------------------------------------
    # [13단계] 미구현 코드 검사
    # --------------------------------------------------------

    # 검사 대상:
    #
    # ① 프로젝트의 main.py
    # ② eda 폴더 아래의 모든 .py 파일
    #
    # glob("*.py"):
    #   → eda 폴더에 있는 파이썬 파일을 찾습니다.
    #
    # sorted():
    #   → 파일 경로를 정렬합니다.
    #
    # *:
    #   → 리스트 안에서 다른 반복 가능한 객체의
    #     항목을 펼쳐 넣는 문법입니다.
    #
    # 예:
    # [main.py, clean.py, analyze.py, plot.py, io_utils.py]
    for path in [
        project / "main.py",
        *sorted((project / "eda").glob("*.py"))
    ]:

        # read_text():
        #   → 파이썬 소스코드를 문자열로 읽습니다.
        #
        # "raise NotImplementedError":
        #   → 아직 구현되지 않은 기능을 표시할 때
        #     사용하는 코드입니다.
        #
        # 해당 문자열이 소스코드에 남아 있다면
        # 미구현 코드로 판단하여 오류를 추가합니다.
        #
        # relative_to(project):
        #   → 프로젝트 폴더를 기준으로 상대 경로를 반환합니다.
        #
        # 예:
        # C:/Project/eda/clean.py
        #          ↓
        # eda/clean.py
        if "raise NotImplementedError" in path.read_text(encoding="utf-8"):
            errors.append(
                "미구현 코드: " + str(path.relative_to(project))
            )

    # --------------------------------------------------------
    # [14단계] 테스트 폴더 존재 여부 검사
    # --------------------------------------------------------

    # tests 폴더는 프로그램이 올바르게 동작하는지
    # 확인하는 테스트 코드나 기록을 관리하는 폴더입니다.
    #
    # .is_dir():
    #   → 해당 경로에 폴더가 존재하는지 검사합니다.
    #
    # tests 폴더가 없으면 오류를 추가합니다.
    #
    # 단, 현재 코드는 tests 폴더의 존재 여부만 검사합니다.
    # 실제 테스트가 정상적으로 통과하는지는 검사하지 않습니다.
    if not (project / "tests").is_dir():
        errors.append("tests 폴더 또는 테스트 기록이 없음")

    # --------------------------------------------------------
    # [15단계] 최종 검증 결과 반환
    # --------------------------------------------------------

    # automatic_errors:
    #   → 프로그램이 자동으로 확인한 오류 목록입니다.
    #
    # manual_review:
    #   → 강사가 직접 확인해야 하는 평가 항목입니다.
    #
    # notice:
    #   → 자동 검사 통과가 최종 승인과 다르다는 안내입니다.
    #
    # 자동 검사 결과가 정상이더라도
    # 보고서의 해석, 코드 작성 과정, Git 이력 등은
    # 추가적인 검토가 필요합니다.
    return {
        "automatic_errors": errors,

        "manual_review": [
            # 원본 데이터를 보호하고 정제 기준을
            # 적절하게 적용했는지 확인합니다.
            "원본 보존·정제 정책 설명",

            # 보고서에 분석 근거 3개와
            # 한계 및 개선안이 포함되어 있는지 평가합니다.
            "보고서의 근거 3개·한계·개선안",

            # 그래프의 축, 단위, 표본 수가
            # 적절하게 표현되어 있는지 확인합니다.
            "그림 축·단위·표본 수의 적절성",

            # 제출자가 코드를 이해하고 있으며
            # 어떤 부분에 기여했는지 확인합니다.
            "코드리뷰와 개인 기여",

            # Git 커밋 이력과 변경 이유를 확인합니다.
            # 실제 커밋은 자동 검사하지 않으므로
            # 사람이 직접 확인해야 합니다.
            "실제 Git 커밋 2개 이상·변경 의도·최종 상태"
        ],

        # 자동 검사는 지정된 조건에 대한 검사 결과입니다.
        # 최종 점수나 제출 승인 여부를 결정하지 않습니다.
        "notice": "자동 검사 통과는 100점 또는 최종 제출 승인과 동일하지 않습니다."
    }


# ============================================================
# 6. 프로그램 실행 및 명령행 인자 처리
# ============================================================

def main():
    """명령행 인자를 읽고 프로젝트 제출물을 검사합니다.

    [실행 예시]

    python validate.py --project ./my_project

    python validate.py --project ./my_project --level applied

    python validate.py --project ./my_project --level advanced

    [명령행 인자]

    --project
        → 검사할 프로젝트 폴더 경로

    --level
        → 실습 난이도
        → basic, applied, advanced 중 하나

    [프로그램 종료 코드]

    0:
        → 자동 검사에서 오류가 발견되지 않음

    1:
        → 자동 검사 오류 또는 파일 처리 오류 발생
    """

    # --------------------------------------------------------
    # [1단계] 명령행 인자 처리 객체 생성
    # --------------------------------------------------------

    # argparse.ArgumentParser():
    #   → 프로그램 실행 옵션을 정의하고 처리합니다.
    #
    # description=__doc__:
    #   → 파일 최상단에 작성한 설명 문자열을
    #     프로그램 도움말에 사용합니다.
    #
    # 예:
    # python validate.py --help
    parser = argparse.ArgumentParser(
        description=__doc__
    )

    # --------------------------------------------------------
    # [2단계] 프로젝트 경로 옵션 정의
    # --------------------------------------------------------

    # --project:
    #   → 검사할 프로젝트 폴더 경로입니다.
    #
    # type=Path:
    #   → 입력한 경로를 Path 객체로 변환합니다.
    #
    # required=True:
    #   → 반드시 입력해야 하는 옵션입니다.
    #
    # 예:
    # python validate.py --project ./my_project
    #
    # --project를 생략하면 argparse가 오류를 출력합니다.
    parser.add_argument(
        "--project",
        type=Path,
        required=True
    )

    # --------------------------------------------------------
    # [3단계] 난이도 옵션 정의
    # --------------------------------------------------------

    # --level:
    #   → 검사할 프로젝트의 난이도를 지정합니다.
    #
    # choices:
    #   → 사용자가 선택할 수 있는 값의 목록입니다.
    #
    # default="basic":
    #   → 별도 지정이 없으면 기본필수 수준으로 검사합니다.
    #
    # 잘못된 난이도를 입력하면 argparse가 오류를 발생시킵니다.
    parser.add_argument(
        "--level",
        choices=["basic", "applied", "advanced"],
        default="basic"
    )

    # --------------------------------------------------------
    # [4단계] 명령행 인자 읽기
    # --------------------------------------------------------

    # parse_args():
    #   → 사용자가 입력한 옵션을 해석합니다.
    #
    # 예:
    # python validate.py --project ./my_project --level applied
    #
    # args.project:
    #   → Path("./my_project")
    #
    # args.level:
    #   → "applied"
    args = parser.parse_args()

    # --------------------------------------------------------
    # [5단계] 제출 프로젝트 검사
    # --------------------------------------------------------

    # try:
    #   → 검사 과정에서 발생할 수 있는 오류를 처리합니다.
    try:

        # inspect_project()에 프로젝트 경로와 난이도를 전달합니다.
        #
        # 함수 내부에서 파일 존재 여부,
        # 통계 결과, 이미지, 보고서 등을 검사합니다.
        #
        # 결과는 딕셔너리 형태로 반환됩니다.
        result = inspect_project(
            args.project,
            args.level
        )

    # --------------------------------------------------------
    # [6단계] 파일 또는 데이터 관련 오류 처리
    # --------------------------------------------------------

    # OSError:
    #   → 파일을 읽지 못하거나 경로에 문제가 있을 때 발생합니다.
    #
    # ValueError:
    #   → 잘못된 값이나 JSON 관련 오류 등이 발생할 수 있습니다.
    #
    # 오류가 발생하면 메시지를 출력하고
    # 종료 코드 1을 반환합니다.
    except (OSError, ValueError) as exc:
        print("검사 실패:", exc)
        return 1

    # --------------------------------------------------------
    # [7단계] 검사 결과 JSON 출력
    # --------------------------------------------------------

    # json.dumps():
    #   → 파이썬 딕셔너리를 JSON 문자열로 변환합니다.
    #
    # ensure_ascii=False:
    #   → 한글을 유니코드 이스케이프 없이 출력합니다.
    #
    # indent=2:
    #   → 들여쓰기 2칸을 적용합니다.
    #
    # 출력 예:
    #
    # {
    #   "automatic_errors": [],
    #   "manual_review": [...],
    #   "notice": "..."
    # }
    print(
        json.dumps(
            result,
            ensure_ascii=False,
            indent=2
        )
    )

    # --------------------------------------------------------
    # [8단계] 종료 코드 반환
    # --------------------------------------------------------

    # result["automatic_errors"]:
    #   → 자동 검사에서 발견한 오류 목록입니다.
    #
    # bool(리스트):
    #   → 빈 리스트 []는 False
    #   → 항목이 있는 리스트는 True
    #
    # int(False) = 0
    # int(True) = 1
    #
    # 따라서 오류가 없다면 0,
    # 오류가 하나라도 있다면 1을 반환합니다.
    return int(bool(result["automatic_errors"]))


# ============================================================
# 7. 프로그램 시작
# ============================================================

# __name__ == "__main__":
#   → 현재 파이썬 파일을 직접 실행했는지 확인합니다.
#
# 직접 실행한 경우:
#   python validate.py --project ./my_project
#
# main() 함수가 호출됩니다.
#
# 다른 파이썬 파일에서 import한 경우:
#   main()이 자동 실행되지 않습니다.
#
# SystemExit():
#   → main()의 반환값을 프로그램 종료 코드로 사용합니다.
#
# 종료 코드:
#   0 → 자동 검사 오류 없음
#   1 → 검사 오류 발견 또는 실행 실패
#
# 참고:
# TODO V_TABLES가 완성되지 않으면
# NotImplementedError가 발생합니다.
# 이 예외는 현재 main()의 except 처리 대상이 아닙니다.
if __name__ == "__main__":
    raise SystemExit(main())
