def validate_tables(clean, summary):
    """정제 데이터와 집계 결과가 서로 일치하는지 검사합니다.

    [입력]

    clean
        → 정제된 개별 실행 기록 DataFrame

    summary
        → 에이전트별 통계가 계산된 DataFrame

    [검사할 내용]

    1. 필수 열이 존재하는가?
    2. 정제 데이터가 비어 있지 않은가?
    3. 실행 ID가 중복되지 않았는가?
    4. 실행 상태가 ok 또는 error인가?
    5. 정제 데이터와 집계 데이터의 agent가 일치하는가?
    6. 전체 실행 횟수가 올바른가?
    7. 유효 측정 횟수가 올바른가?
    8. 평균과 중앙값이 올바른가?
    9. 성공률과 성공 백분율이 올바른가?

    [반환값]

    오류 문장을 담은 리스트를 반환합니다.

    문제가 없으면:
        []

    문제가 있으면:
        ["필수 열 누락", "상태 허용값 위반", ...]

    즉, 오류가 발생했다고 프로그램을 바로 종료하는 것이 아니라
    발견한 오류를 리스트에 모아 반환하는 방식입니다.
    """

    # --------------------------------------------------------
    # [1단계] 필수 열 목록 정의
    # --------------------------------------------------------

    # needed:
    #   → 정제 데이터에 반드시 존재해야 하는 열 이름입니다.
    #
    # 중괄호 { }는 파이썬의 집합(set)을 의미합니다.
    #
    # 집합은 중복을 허용하지 않으며
    # 원소의 포함 여부를 검사할 때 유용합니다.
    #
    # run_id:
    #   → 실행 기록의 고유 식별자
    #
    # agent:
    #   → AI 에이전트의 이름 또는 역할
    #
    # latency_ms:
    #   → 실행 시간(밀리초)
    #
    # tokens:
    #   → 사용한 토큰 개수
    #
    # status:
    #   → 실행 상태(ok 또는 error)
    #
    # day:
    #   → 실행 날짜
    needed = {
        "run_id",
        "agent",
        "latency_ms",
        "tokens",
        "status",
        "day"
    }

    # summary_needed:
    #   → 에이전트별 요약 데이터에 필요한 열입니다.
    #
    # runs:
    #   → 전체 실행 횟수
    #
    # measured:
    #   → 유효한 실행 시간이 존재하는 기록 수
    #
    # mean_ms:
    #   → 평균 실행 시간
    #
    # median_ms:
    #   → 실행 시간의 중앙값
    #
    # success_rate:
    #   → 성공 비율(0~1)
    #
    # success_pct:
    #   → 성공 백분율(0~100)
    summary_needed = {
        "agent",
        "runs",
        "measured",
        "mean_ms",
        "median_ms",
        "success_rate",
        "success_pct"
    }

    # --------------------------------------------------------
    # [2단계] 필수 열 존재 여부 검사
    # --------------------------------------------------------

    # issubset():
    #   → 한 집합의 모든 원소가 다른 집합에 포함되어 있는지 확인합니다.
    #
    # 예:
    # {"A", "B"}.issubset({"A", "B", "C"})
    #   → True
    #
    # {"A", "D"}.issubset({"A", "B", "C"})
    #   → False
    #
    # clean.columns:
    #   → 정제 DataFrame의 열 이름 목록
    #
    # summary.columns:
    #   → 집계 DataFrame의 열 이름 목록
    #
    # not:
    #   → True와 False를 반대로 바꿉니다.
    #
    # 두 데이터 중 하나라도 필수 열이 누락되었다면
    # 이후 검사를 진행할 수 없으므로 오류 목록을 반환합니다.
    if (
        not needed.issubset(clean.columns)
        or not summary_needed.issubset(summary.columns)
    ):
        return ["필수 열 누락"]

    # --------------------------------------------------------
    # [3단계] 오류 목록 생성
    # --------------------------------------------------------

    # 발견한 오류 메시지를 저장할 빈 리스트입니다.
    #
    # 오류를 발견할 때마다 append()로 추가합니다.
    #
    # 모든 검사를 통과하면 빈 리스트가 반환됩니다.
    errors = []

    # --------------------------------------------------------
    # [4단계] 정제 데이터와 실행 ID 검사
    # --------------------------------------------------------

    # clean.empty:
    #   → DataFrame이 비어 있는지 확인합니다.
    #
    # clean["run_id"].is_unique:
    #   → 모든 실행 ID가 고유한지 확인합니다.
    #
    # clean["run_id"].isna().any():
    #   → 실행 ID에 결측값이 하나라도 있는지 확인합니다.
    #
    # or:
    #   → 조건 중 하나라도 True이면 전체 조건이 True입니다.
    #
    # 다음 경우 오류를 추가합니다.
    #
    # ① 데이터가 비어 있는 경우
    # ② 실행 ID가 중복된 경우
    # ③ 실행 ID에 결측값이 있는 경우
    if (
        clean.empty
        or not clean["run_id"].is_unique
        or clean["run_id"].isna().any()
    ):
        errors.append("빈 정제표 또는 ID 고유성 위반")

    # --------------------------------------------------------
    # [5단계] 실행 상태(status) 검사
    # --------------------------------------------------------

    # isin(["ok", "error"]):
    #   → 각 status 값이 허용된 목록에 포함되는지 검사합니다.
    #
    # all():
    #   → 모든 값이 True인지 확인합니다.
    #
    # 예:
    # ["ok", "error", "ok"] → 정상
    # ["ok", "unknown"]     → 오류
    #
    # 알 수 없는 상태를 임의로 실패 처리하면
    # 성공률 계산이 잘못될 수 있습니다.
    if not clean["status"].isin(["ok", "error"]).all():
        errors.append("상태 허용값 위반")

    # --------------------------------------------------------
    # [6단계] 에이전트 역할 키 검사
    # --------------------------------------------------------

    # summary["agent"].is_unique:
    #   → 집계 결과에서 agent가 중복되지 않았는지 확인합니다.
    #
    # set(summary["agent"]):
    #   → 집계 결과의 agent 이름을 집합으로 변환합니다.
    #
    # set(clean["agent"]):
    #   → 정제 데이터의 agent 이름을 집합으로 변환합니다.
    #
    # 두 집합을 비교하여 에이전트 구성의 일치 여부를 확인합니다.
    #
    # 예:
    # clean   = {"planner", "coder"}
    # summary = {"planner", "coder"}
    #   → 정상
    #
    # clean   = {"planner", "coder"}
    # summary = {"planner"}
    #   → 오류
    #
    # 에이전트 정보가 일치하지 않으면
    # 역할별 통계를 정확하게 비교할 수 없으므로
    # 현재까지 발견한 오류와 함께 반환합니다.
    if (
        not summary["agent"].is_unique
        or set(summary["agent"]) != set(clean["agent"])
    ):
        return errors + ["요약 역할 키 불일치"]

    # --------------------------------------------------------
    # [7단계] 에이전트별 통계 검사
    # --------------------------------------------------------

    # summary.to_dict(orient="records"):
    #   → DataFrame의 각 행을 딕셔너리로 변환합니다.
    #
    # 예:
    #
    # [
    #     {"agent": "planner", "runs": 10},
    #     {"agent": "coder", "runs": 20}
    # ]
    #
    # for 문으로 각 에이전트의 요약 결과를 하나씩 확인합니다.
    for row in summary.to_dict(orient="records"):

        # 현재 검사 중인 에이전트의 실행 기록만 선택합니다.
        #
        # row["agent"]:
        #   → 현재 집계 행의 에이전트 이름
        #
        # clean["agent"].eq(row["agent"]):
        #   → agent 이름이 같은 행인지 검사합니다.
        #
        # .loc[조건]:
        #   → 조건을 만족하는 행을 선택합니다.
        #
        # part에는 특정 에이전트의 전체 실행 기록이 들어갑니다.
        # 성공과 실패 기록이 모두 포함됩니다.
        part = clean.loc[
            clean["agent"].eq(row["agent"])
        ]

        # 실행 시간이 정상적으로 측정된 데이터만 선택합니다.
        #
        # dropna():
        #   → NaN을 제외합니다.
        #
        # values에는 실행 시간이 존재하는 값만 남습니다.
        #
        # 예:
        # [100, 200, NaN, 400]
        #          ↓
        # [100, 200, 400]
        values = part["latency_ms"].dropna()

        # ====================================================
        # TODO V_TABLES: 수강생이 직접 구현할 부분
        # ====================================================
        #
        # [목표]
        # 현재 에이전트의 실제 실행 기록(part)을 사용하여
        # 6가지 통계를 다시 계산합니다.
        #
        # 그리고 집계 결과(summary)에 저장된 값과 비교할
        # expected 딕셔너리를 생성합니다.
        #
        # [필요한 변수]
        #
        # part:
        #   → 현재 에이전트의 전체 실행 기록
        #
        # values:
        #   → 실행 시간이 유효한 기록만 모은 데이터
        #
        # [계산해야 할 통계]
        #
        # ① runs: 전체 실행 횟수
        #
        #    성공과 실패를 포함한 전체 기록 수입니다.
        #
        #    예:
        #    실행 기록 10건 → runs = 10
        #
        # ② measured: 유효 실행 시간 개수
        #
        #    latency_ms가 NaN이 아닌 기록의 개수입니다.
        #
        #    예:
        #    전체 10건 중 8건만 시간이 측정되었다면
        #    measured = 8
        #
        # ③ mean_ms: 평균 실행 시간
        #
        #    유효한 실행 시간만 사용하여 계산합니다.
        #
        #    예:
        #    [100, 200, NaN]
        #
        #    평균 = (100 + 200) / 2 = 150
        #
        #    NaN을 0으로 바꾸거나 전체 3건으로
        #    나누면 잘못된 평균이 됩니다.
        #
        # ④ median_ms: 중앙값
        #
        #    유효한 실행 시간을 정렬했을 때
        #    중앙에 위치한 값입니다.
        #
        #    예:
        #    [100, 200, 900]
        #
        #    중앙값 = 200
        #
        # ⑤ success_rate: 성공률
        #
        #    전체 실행 중 status가 "ok"인 비율입니다.
        #
        #    성공률 = 성공 실행 횟수 / 전체 실행 횟수
        #
        #    중요한 점:
        #    성공률의 분모는 values가 아니라 part입니다.
        #
        #    즉, 실행 시간이 결측인 기록도
        #    전체 실행 횟수에 포함됩니다.
        #
        # ⑥ success_pct: 성공 백분율
        #
        #    성공률에 100을 곱하여 계산합니다.
        #
        #    예:
        #    success_rate = 0.8
        #    success_pct = 80.0
        #
        # [결측값 처리]
        #
        # 유효한 실행 시간이 0건인 경우
        # 평균과 중앙값은 계산할 수 없습니다.
        #
        # 따라서 mean_ms와 median_ms에
        # np.nan을 사용해야 합니다.
        #
        # 단, 성공률은 전체 실행 기록으로 계산하므로
        # 실행 시간이 없더라도 성공 상태 정보로 계산할 수 있습니다.
        #
        # [구현 결과]
        #
        # expected는 다음 키를 가진 딕셔너리여야 합니다.
        #
        # expected = {
        #     "runs": ...,
        #     "measured": ...,
        #     "mean_ms": ...,
        #     "median_ms": ...,
        #     "success_rate": ...,
        #     "success_pct": ...
        # }
        #
        # [참고할 함수]
        #
        # len()         : 데이터 개수
        # .mean()       : 평균 계산
        # .median()     : 중앙값 계산
        # .eq("ok")     : status가 ok인지 검사
        # np.nan        : 숫자 결측값
        #
        # 아래 오류는 구현을 완료하면 제거합니다.
        raise NotImplementedError("TODO V_TABLES")

        # ----------------------------------------------------
        # [8단계] 계산값과 저장된 집계값 비교
        # ----------------------------------------------------

        # expected.items():
        #   → 딕셔너리의 키와 값을 하나씩 가져옵니다.
        #
        # key:
        #   → runs, measured, mean_ms 등의 통계 이름
        #
        # value:
        #   → 원본 기록으로 다시 계산한 예상값
        #
        # row[key]:
        #   → 제출된 summary에 저장되어 있는 실제 값
        for key, value in expected.items():

            # 제출된 요약 통계에서 해당 값을 가져옵니다.
            actual = row[key]

            # [8-1] 두 값이 모두 결측값인지 검사합니다.
            #
            # pd.isna():
            #   → NaN, None 등의 결측값인지 확인합니다.
            #
            # 두 값이 모두 NaN이면
            # 결측 상태가 동일하므로 다음 통계로 넘어갑니다.
            #
            # continue:
            #   → 현재 반복을 종료하고 다음 반복으로 이동합니다.
            if pd.isna(value) and pd.isna(actual):
                continue

            # [8-2] 실수 계산 결과를 비교합니다.
            #
            # math.isclose():
            #   → 두 실수가 허용 오차 범위 내에서
            #     거의 같은 값인지 확인합니다.
            #
            # 부동소수점 계산에서는 미세한 오차가 발생할 수 있습니다.
            #
            # 예:
            # 0.1 + 0.2의 계산 결과는
            # 내부적으로 0.30000000000000004가 될 수 있습니다.
            #
            # 따라서 소수 계산 결과를 비교할 때
            # 단순 == 대신 isclose()를 활용합니다.
            #
            # rel_tol=1e-8:
            #   → 상대 오차 허용 범위
            #
            # abs_tol=1e-8:
            #   → 절대 오차 허용 범위
            try:
                same = math.isclose(
                    float(actual),
                    float(value),
                    rel_tol=1e-8,
                    abs_tol=1e-8
                )

            # 숫자로 변환할 수 없거나 자료형에 문제가 있으면
            # 동일하지 않은 값으로 판단합니다.
            except (TypeError, ValueError):
                same = False

            # [8-3] 계산 결과가 다르면 오류를 추가합니다.
            #
            # f-string:
            #   → 문자열 안에 변수 값을 삽입합니다.
            #
            # 예:
            # planner.mean_ms: 분모/수치 불일치
            #
            # 어떤 에이전트의 어떤 통계가 잘못되었는지
            # 확인할 수 있도록 오류 문장을 생성합니다.
            if not same:
                errors.append(
                    f'{row["agent"]}.{key}: 분모/수치 불일치'
                )

    # 모든 에이전트의 검사를 마친 뒤
    # 발견한 오류 메시지 목록을 반환합니다.
    return errors


